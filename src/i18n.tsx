const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: typeof en } | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return localStorage.getItem('medicare-lang') === 'hi' ? 'hi' : 'en'
    } catch {
      return 'en'
    }
  })

  const setLang = (next: Lang) => {
    setLangState(next)
    localStorage.setItem('medicare-lang', next)
  }

  useEffect(() => {
    document.documentElement.lang = lang === 'hi' ? 'hi' : 'en'
  }, [lang])

  return <LangCtx.Provider value={{ lang, setLang, t: lang === 'hi' ? hi : en }}>{children}</LangCtx.Provider>
}

export function useLang() {
  const ctx = useContext(LangCtx)
  if (!ctx) throw new Error('useLang')
  return ctx
}

export function categoryLabel(lang: Lang, cat: string) {
  return CATEGORY_LABEL[lang][cat] ?? cat
}

export function fill(template: string, n: number) {
  return template.replace('{n}', String(n))
}
